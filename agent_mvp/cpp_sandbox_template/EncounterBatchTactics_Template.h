#pragma once

#include <string>
#include <vector>

#include "../../Source/Tools/interface.h"

namespace EncounterBatchTemplate {

// Task-level metadata passed from the runner into the tactic module.
struct TacticalTaskConfig {
    std::string task_id;
    int tactic_id = 0;
    int team = 0;
    int red_unit_count = 0;
    int blue_unit_count = 0;
};

// A runner-owned observation view. Tactical teams should treat this as the
// stable input surface for rule logic or RL inference.
struct UnitObservation {
    int plane_id = -1;
    int team = 0;
    bool alive = false;
    bool target_locked = false;
    int missile_count = 0;
    int warning_count = 0;
    int inbound_missile_count = 0;
    double lon = 0.0;
    double lat = 0.0;
    double alt = 0.0;
    double speed = 0.0;
};

struct TeamStepInput {
    TacticalTaskConfig task;
    int step_index = 0;
    double dt = 0.1;
    std::vector<UnitObservation> self_units;
    std::vector<UnitObservation> enemy_units;
};

// A tactic-owned command surface. The runner translates these high-level
// commands into PlaneState_S fields, then advances the environment.
struct UnitCommand {
    int plane_id = -1;
    int target_id = -1;
    bool fire = false;
    bool evade = false;
    double desired_lon = 0.0;
    double desired_lat = 0.0;
    double desired_alt = 5000.0;
    double desired_speed = 300.0;
    RadarState_E radar_state = RadarState_E::Scan;
    std::string debug_role;
};

// This controller is the tactical-team integration template.
//
// Recommended workflow:
// 1. Keep EncounterBatchRunner_Template.cpp as the orchestrator.
// 2. Replace BuildRuleBasedCommands() with your own rule tactic, or
// 3. Load an RL model and replace BuildRlInferenceCommand().
//
// The Python side does not care how commands are produced. It only depends on
// the final episodes.jsonl contract generated by the runner.
class TemplateTacticController {
public:
    explicit TemplateTacticController(int team);

    void StartTask(const TacticalTaskConfig& task);
    std::vector<UnitCommand> BuildStepCommands(const TeamStepInput& input);
    void FinishTask();

private:
    // Tactical teams can flip this to route through an RL policy instead of
    // the default rule placeholder.
    bool UseRlPolicy() const;

    // Rule-based hook: replace this if your team implements tactics with
    // handcrafted logic.
    std::vector<UnitCommand> BuildRuleBasedCommands(const TeamStepInput& input) const;

    // RL hook: load a trained policy and return one command per alive unit.
    UnitCommand BuildRlInferenceCommand(
        const UnitObservation& self,
        const TeamStepInput& input,
        const UnitObservation* focus_target) const;

    const UnitObservation* SelectFocusTarget(const TeamStepInput& input) const;
    const UnitObservation* SelectNearestEnemy(
        const UnitObservation& self,
        const std::vector<UnitObservation>& enemies) const;

    int team_ = 0;
    TacticalTaskConfig current_task_;
    bool use_rl_policy_ = false;
};

} // namespace EncounterBatchTemplate
